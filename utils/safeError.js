// অ্যাডমিন/ইউজার-মুখী এরর মেসেজের জন্য একটাই সিদ্ধান্ত-বিন্দু।
//
// সমস্যাটা ছিল: অনেক হ্যান্ডলারে `catch (err) { req.flash('error', err.message) }`
// লেখা ছিল। ওই একই try ব্লকে দুই ধরনের এরর আসতে পারে —
//
//   ১) ইচ্ছাকৃত ভ্যালিডেশন এরর (যেমন "এই নামে ইতিমধ্যে একটা Role আছে।") — এগুলো
//      অ্যাডমিনকে দেখানোই উদ্দেশ্য, না দেখালে UI অকেজো হয়ে যায়;
//   ২) অপ্রত্যাশিত ইন্টারনাল এরর (pg/ফাইলসিস্টেম/নেটওয়ার্ক) — এর মেসেজে টেবিল-কলামের
//      নাম, কনস্ট্রেইন্টের নাম, সার্ভারের ফাইল পাথ, কানেকশন স্ট্রিং পর্যন্ত থাকতে পারে।
//
// শুধু err.message ছাপালে (২) লিক হয়; আবার সব catch-এ জেনেরিক বার্তা বসালে (১) হারিয়ে
// যায় এবং বিদ্যমান ইচ্ছাকৃত আচরণ ভেঙে যায়। তাই এরর তৈরির জায়গাতেই স্পষ্টভাবে চিহ্নিত
// করা হয় কোনটা পাবলিক: PublicError (expose === true)। অন্য সবকিছু ডিফল্টে ইন্টারনাল।
//
// publicMessage() তাই fail-safe: চেনা-পাবলিক না হলে fallback বার্তাই ফেরত যায়।
// পূর্ণ কারণটা কলারের console.error()-এ (সার্ভার লগে) আগের মতোই থাকে।
// ---------------------------------------------------------------------------

class PublicError extends Error {
  constructor(message) {
    super(message);
    this.name = 'PublicError';
    this.expose = true;
  }
}

/**
 * @param {unknown} err     ধরা পড়া এরর
 * @param {string}  fallback  ইন্টারনাল এররের জন্য নিরাপদ, পড়ার মতো বার্তা (বাংলা)
 * @returns {string} ব্রাউজারে পাঠানোর জন্য নিরাপদ বার্তা
 */
function publicMessage(err, fallback) {
  if (err && err.expose === true && typeof err.message === 'string' && err.message.trim()) {
    return err.message;
  }
  return fallback;
}

module.exports = { PublicError, publicMessage };
